/** 文本像素宽（右对齐/居中靠它，不用再猜 `len*6`）。 */
export function textWidth(text: string, scale = 1): number {
  if (!text) return 0;
  return (text.length * ADVANCE - GLYPH_GAP) * scale;
}

/**
 * 把一个字符串画到 `(x, y)`。
 *
 * 性能上做了**横向游程合并**：一行里的连续亮像素合成一个 `fillRect`，
 * 一帧几十个字符只发几十次调用（逐像素画会发上千次）。
 */
export function drawText(
  ctx: SKRSContext2D,
  x: number,
  y: number,
  text: string,
  color: Rgb,
  scale = 1,
  alpha = 255,
): void {
  ctx.fillStyle = rgba(color, alpha);
  const up = text.toUpperCase();
  for (let i = 0; i < up.length; i++) {
    const rows = GLYPHS[up[i]];
    if (!rows) continue; // 没做这个字形就留空，不画方框
    const ox = x + i * ADVANCE * scale;
    for (let ry = 0; ry < GLYPH_H; ry++) {
      const row = rows[ry];
      let run = 0;
      for (let rx = 0; rx <= GLYPH_W; rx++) {
        if (rx < GLYPH_W && row[rx] === '#') {
          run++;
          continue;
        }
        if (run > 0) {
          ctx.fillRect(ox + (rx - run) * scale, y + ry * scale, run * scale, scale);
          run = 0;
        }
      }
    }
  }
}
/**
 * 5×7 点阵字体 —— 自绘，硬边、无抗锯齿。
 *
 * 为什么不用系统字体：像素画配矢量字体会发虚、宽度不齐，右对齐只能靠
 * `len(name)*6` 硬猜（用户名一长就飘）。点阵字体每个字都是 6px 步进，
 * 宽度可精确计算，配像素画才对味。
 *
 * 字形约定：5 列 × 7 行，`#` = 亮、`.` = 空。只实现大写字母（`drawText` 自动大写）。
 */
import type { SKRSContext2D } from '@napi-rs/canvas';
import { rgba, type Rgb } from './config.js';

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const GLYPH_GAP = 1;
export const ADVANCE = GLYPH_W + GLYPH_GAP; // 每字符 6px

function g(...rows: string[]): string[] {
  if (rows.length !== GLYPH_H) {
    throw new Error(`字形要有 ${GLYPH_H} 行，收到 ${rows.length}`);
  }
  for (const r of rows) {
    if (r.length !== GLYPH_W) {
      throw new Error(`字形每行要 ${GLYPH_W} 列，收到 ${r.length}: ${r}`);
    }
  }
  return rows;
}


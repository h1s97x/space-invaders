# ── 开火节奏 ────────────────────────────────────────────────────────
# 射速**不是**独立旋钮：它被绑到飞船的横向位移上 —— 每走过一整列才开一枪。
#
# 为什么必须这样：射速和飞船速度是两个强耦合的量。飞船慢、射速快时，
# 它会停在已清空的列上一发接一发地空放（实测 60% 的子弹打空，
# 清场率 238/268 → 84/268）；飞船快、射速慢则整场打不完。
# 改成「位移触发」后射速是派生量：shots/s = v / FIRE_SPACING × fps，
# 调飞船速度射速自动跟着走，两者不可能再打架。
# 2 帧：飞船 4.5px/帧、列距 15px → 跨一列要 3.3 帧。取 3 的话高速掠过时会被
# 这条 guard 挡掉（漏列 → 事后得专门跑回来补一趟，反而更慢），取 2 才不拖后腿。

def _rgba(color: Tuple[int, int, int], alpha: int = 255) -> Tuple[int, int, int, int]:
    """把 RGB 调色板常量补成 RGBA —— 所有实体都画在 RGBA 透明图层上。

    GIF 只支持 1 位「全透明/不透明」，没有半透明，所以 alpha 必须在
    「合成到背景」这一步就消耗掉（见 `render.Renderer.render`），
    不能指望编码器。alpha=255 即完全不透明，与原先用 RGB 绘制等价。
    """
    return (color[0], color[1], color[2], max(0, min(255, int(alpha))))



# 默认播放帧率。注意 fps **只**决定 GIF 的每帧时长（frame_ms），
# 不影响逻辑步长、帧数与体积 —— 帧数不变、体积不变、内存不变。
#
# 为什么是 25 而不是原来的 20：穿透从 8 降到 3 之后，「停在同一列补枪」的段落
# 变多，整场逻辑帧数从约 600 涨到约 990。帧数由**逻辑**决定，改 fps 动不了它，
# 但**播放时长**可以用 fps 免费压回来：990 帧 @20fps = 49.5s，@25fps = 39.6s，
# 而体积与清晰度分毫未损。选 25 而不是 40，是给动作留出可读的从容感
# （再快就又变回「看不清在打什么」了）。

# 命中停顿（hit-stop）：打爆格子的瞬间飞船要有一下顿挫 —— 射击游戏的打击感
# 来自「击中那一刻的微卡顿」，而不是爆炸粒子本身。有了它，逐格清除才是一记一记
# 有颗粒感的连击，而不是同一帧里分别发生了几件事。
#
# 但**实心凝固太贵**：268 个格子每格凝固 2 帧就是 +536 帧（≈27s），实测整场
# 会从约 600 帧涨到 1260 帧。所以分两档：
#   * 普通格 → 减速 HIT_STOP_SPEED_SCALE（＝「抽一下」）：几乎不花帧数，
#     但打爆那一刻飞船仍有可见的顿挫；
#   * level>=4 / BOSS 宿主（稀有的重音）→ 真·凝固 HIT_STOP_FRAMES 帧。
# 重音之所以成立，恰恰因为它稀有 —— 全场停顿时刻就那么几十个。

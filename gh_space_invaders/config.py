HIT_STOP_SPEED_SCALE = 0.2   # 普通命中的顿挫强度：0=彻底钉死 1=完全没感觉

# 随机策略：候选列数 + 距离加权（数值照抄参考项目 RandomStrategy 的 8 / 10 / 100 / 1）。
# 就近为主换效率，长尾的 1 保留「跳到远处」的意外 —— 随机性来自这里。
GOAL_CANDIDATES = 8
W_SAME, W_NEAR, W_FAR = 10, 100, 1

# 方向惯性：与当前航向一致的候选列，权重 ×N。**默认 32（强惯性）**。
#
# 这一条的结论被实测推翻过一次，值得把过程记下来：
#   早先默认 1（关闭），理由是「惯性会把轨迹压成单向推进 —— 更省时但更机械」。
#   那是把「变向次数多」直接当成了「不机械」，而没去看二向 нами多少次是废料：
#      bias=1  → 1002 帧，27 次方向反转，其中 **25 次是不到 1.5 列的微幅抖动**
#      bias=32 →  829 帧，只剩 6 次反转，轨迹反而更短更连贯
#   也就是说：没有惯性时，飞船每清完一列就在近邻之间重新抽签，表现出来就是
#   「左右抽搐」；正常人玩游戏是「沿一个方向连续扫过去，扫到头再回来补漏」。
#
# 于是随机性重新分工：**大方向交给惯性（连贯），变化交给 SKIP_CHANCE（放进
# 遗漏、回头补）** —— 两者各管一件事，才既连贯又有抑扬。
GOAL_DIR_BIAS = 32

# 「放过这一列」的概率：飞船掠过某列时，有这个概率不开火，留到回头再补。
#
# 为什么必须有这一条：飞船一边走一边把经过的列都清掉（穿透 8，一发一列），
# 于是前方永远有目标、后方永远是空的 —— 目标无论怎么随机选，实际轨迹都会
# 退化成「一路推到底再折返」的单向扫荡，也就是之前那个「机械」的观感。
# 放过一些列，才会出现「扫过去 → 漏了两列 → 掉头补掉 → 继续」这种起伏。
# 代价是路径变长（回头要重走），所以这个值直接决定时长，别乱调。
SKIP_CHANCE = 0.15

# ── BOSS：从「随机彩蛋」改成「结构化的收尾阶段」────────────────────────────
#
# 旧设计是「level>=4 的格子按概率随机飞出 BOSS」，三个问题：
#   1. 时机与位置全随机 → 爱冒不冒，也无法塑造中段高潮；
#   2. BOSS 与清场互不咬合（清场判定只数 targets）→ 它成了打完也没人管的孤儿；
#   3. 飞船没有血量，BOSS 打过来只扣分不致命 → 威胁是假的，纯粹是干扰。
# 新设计把 BOSS 钉成可预期的阶段事件：
#   开局先挑定 BOSS_HOST_COUNT 个高贡献格当「宿主」→ 只有等清场过半之后，
#   这些宿主被打爆才化身 BOSS（不再到处掷骰子）→ 且必须把它打掉才算真正清场。

# 化身为 BOSS 的高贡献格个数（按贡献从高到低挑）

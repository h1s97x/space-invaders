def text_width(text: str, scale: int = 1) -> int:
    """文本像素宽（右对齐/居中就靠它，不用再猜 `len()*6`）。"""
    if not text:
        return 0
    return (len(text) * ADVANCE - GAP) * scale


def draw_text(d: ImageDraw.ImageDraw, xy: Tuple[int, int], text: str,
              color: Tuple[int, int, int], scale: int = 1,
              alpha: int = 255) -> None:
    """把一个字符串画到 `(x, y)`。

    实现上把所有亮像素攒成一个坐标列表、最后只发一次 `d.point(...)`，
    一帧里几十个字符也只有几十次调用（逐像素画会是上千次）。
    """
    x0, y0 = xy
    pts: List[Tuple[int, int]] = []
    for i, ch in enumerate(text.upper()):
        rows = GLYPHS.get(ch)
        if rows is None:
            continue                      # 没做这个字形就留空，不画方框
        ox = x0 + i * ADVANCE * scale
        for ry, row in enumerate(rows):
            for rx, cell in enumerate(row):
                if cell == ".":
                    continue
                px, py = ox + rx * scale, y0 + ry * scale
                if scale == 1:
                    pts.append((px, py))
                else:
                    d.rectangle([px, py, px + scale - 1, py + scale - 1],
                                fill=_rgba(color, alpha))
    if pts:
        d.point(pts, fill=_rgba(color, alpha))


def glyph_names() -> Sequence[str]:
    return tuple(sorted(GLYPHS))
